"""Generate every catalog and browse artifact from the product folders.

    uv run scripts/build_catalog.py           # write generated files
    uv run scripts/build_catalog.py --check   # fail if any are stale (CI)

Inputs:  products/*/plugin.json, products/*/skills/*/catalog-entry.json,
         catalog/pointers.json, catalog/owners.json
Outputs: .claude-plugin/marketplace.json   (Claude Code; also read by Copilot)
         .agents/plugins/marketplace.json  (Codex)
         CATALOG.md, THIRD_PARTY_NOTICES.md, UPSTREAMS.md

Never edit the outputs by hand; edit the inputs and re-run.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import catalog_lib as cl

REPO_URL = "https://github.com/IBM/agentic-ai-labs-skills"
MARKETPLACE_DESCRIPTION = (
    "Agent skills for IBM products, packaged for Claude Code, Codex, GitHub Copilot, "
    "Cursor, IBM Bob, and other coding agents."
)
OWNER = {"name": "Agentic AI Labs"}
AGENT_LABELS = {
    "claude-code": "Claude Code",
    "codex": "Codex",
    "bob": "Bob",
    "copilot": "Copilot",
    "cursor": "Cursor",
}
MD_HEADER = (
    "<!-- Copyright contributors to the Agentic AI Labs project -->\n"
    "<!-- SPDX-License-Identifier: Apache-2.0 -->\n"
    "<!-- GENERATED by scripts/build_catalog.py from products/ and catalog/. Do not edit by hand. -->\n\n"
)


class BuildError(Exception):
    pass


def _json(data) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def _md_cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def _upstream_link(up: dict) -> str:
    owner_repo = cl.parse_github_url(up.get("url", ""))
    label = "/".join(owner_repo) if owner_repo else up.get("url", "")
    url = f"{up.get('url', '').rstrip('/')}/tree/{up.get('ref', '')}/{up.get('path', '').strip('/')}"
    return f"[{label}]({url})"


def skill_kind(skill: cl.Skill) -> str:
    if skill.status == "imported":
        return "imported"
    if skill.name.endswith("-ops"):
        return "ops"
    if skill.name.endswith("-build"):
        return "build"
    return "skill"


def verification_cell(skill: cl.Skill) -> str:
    verified = (skill.entry or {}).get("verified") or {}
    current = cl.parse_semver(skill.product.version or "")
    parts = []
    for agent in cl.AGENTS:
        value = verified.get(agent)
        if not value:
            continue
        m = cl.VERIFIED_RE.match(value)
        version = m.group(2) if m else "?"
        if current and cl.parse_semver(version) and cl.parse_semver(version) < current:
            parts.append(f"{AGENT_LABELS[agent]} (stale: {version})")
        else:
            parts.append(f"{AGENT_LABELS[agent]} ✓")
    return ", ".join(parts) if parts else "unverified"


def claude_marketplace(products) -> dict:
    plugins = []
    for p in products:
        m = p.manifest
        entry = {"name": m["name"], "description": m["description"]}
        if m.get("author"):
            entry["author"] = m["author"]
        entry["source"] = f"./products/{p.slug}"
        entry["version"] = m["version"]
        plugins.append(entry)
    return {
        "$schema": "https://anthropic.com/claude-code/marketplace.schema.json",
        "name": cl.MARKETPLACE_NAME,
        "description": MARKETPLACE_DESCRIPTION,
        "owner": OWNER,
        "plugins": plugins,
    }


def codex_marketplace(products) -> dict:
    plugins = []
    for p in products:
        plugins.append({
            "name": p.manifest["name"],
            "source": {"source": "local", "path": f"./products/{p.slug}"},
            "policy": {"installation": "AVAILABLE", "authentication": "ON_INSTALL"},
            "category": p.extension.get("category", "Developer tools"),
        })
    return {
        "name": cl.MARKETPLACE_NAME,
        "interface": {"displayName": "Agentic AI Labs: IBM skills"},
        "plugins": plugins,
    }


def catalog_md(products, pointers) -> str:
    out = [MD_HEADER, "# Skills catalog\n\n"]
    out.append(
        "Every IBM product skill in this repository, with its status and where it was "
        "verified. See the [README](README.md) for install instructions per agent.\n\n"
        "- **maintained**: authored and maintained in this repository.\n"
        "- **imported**: copied from an upstream project at a pinned commit, with "
        "attribution (see [THIRD_PARTY_NOTICES.md](THIRD_PARTY_NOTICES.md)).\n"
        "- **Verified**: agents a maintainer has tested the skill in. *stale* means the "
        "skill changed since that verification.\n\n"
    )
    for p in products:
        m = p.manifest
        title = p.extension.get("displayName") or m["name"]
        out.append(f"## {title}\n\n")
        out.append(f"Plugin `{m['name']}` v{m['version']}: {_md_cell(m['description'])}\n\n")
        out.append("| Skill | Kind | Status | Verified | Source |\n|---|---|---|---|---|\n")
        for s in p.skills:
            entry = s.entry or {}
            if s.status == "imported":
                up = entry.get("upstream") or {}
                source = f"{_upstream_link(up)} ({entry.get('license', '?')})"
            else:
                source = "this repository"
            out.append(
                f"| [`{s.name}`](products/{p.slug}/skills/{s.name}/SKILL.md) | {skill_kind(s)} "
                f"| {s.status} | {verification_cell(s)} | {source} |\n"
            )
        out.append("\n")
    if pointers:
        out.append("## Pointers (not redistributed)\n\n")
        out.append(
            "These upstream skills are listed for discovery only. Their license (or an open "
            "question) prevents copying them here; install them from upstream.\n\n"
            "| Skill | Products | License | Upstream | Why it is a pointer |\n|---|---|---|---|---|\n"
        )
        for ptr in sorted(pointers, key=lambda x: x.get("name", "")):
            out.append(
                f"| `{ptr['name']}` | {', '.join(ptr.get('products', []))} | {ptr.get('license', '?')} "
                f"| {_upstream_link(ptr)} | {_md_cell(ptr.get('reason', ''))} |\n"
            )
        out.append("\n")
    return "".join(out).rstrip("\n") + "\n"


def notices_md(products) -> str:
    out = [MD_HEADER, "# Third-party notices\n\n"]
    out.append(
        "This repository includes skills copied from the upstream projects below, each at a "
        "pinned commit and under its own license. Each copied skill folder contains the "
        "upstream LICENSE file; this repository's Apache-2.0 license does not apply to them.\n\n"
    )
    rows = [
        (p, s) for p in products for s in p.skills if s.status == "imported"
    ]
    if not rows:
        out.append("No third-party skills are currently included.\n")
        return "".join(out)
    out.append("| Skill | Upstream | Commit | License | Authors | Modified |\n|---|---|---|---|---|---|\n")
    for p, s in sorted(rows, key=lambda r: r[1].name):
        e = s.entry or {}
        up = e.get("upstream") or {}
        modified = "yes (see catalog-entry.json)" if e.get("modified") else "no"
        out.append(
            f"| [`{s.name}`](products/{p.slug}/skills/{s.name}) | {_upstream_link(up)} "
            f"| `{up.get('ref', '')[:12]}` | {e.get('license', '?')} "
            f"| {_md_cell(', '.join(e.get('authors') or []))} | {modified} |\n"
        )
    return "".join(out)


def upstreams_md(products, pointers, owners) -> str:
    repos: dict[str, dict] = {}

    def slot(url: str) -> dict:
        owner_repo = cl.parse_github_url(url)
        key = "/".join(owner_repo) if owner_repo else url
        return repos.setdefault(key, {"url": url, "products": set(), "licenses": set(), "imported": 0, "pointers": 0})

    for p in products:
        for s in p.skills:
            if s.status == "imported":
                up = (s.entry or {}).get("upstream") or {}
                r = slot(up.get("url", ""))
                r["products"].add(p.slug)
                r["licenses"].add((s.entry or {}).get("license", "?"))
                r["imported"] += 1
    for ptr in pointers:
        r = slot(ptr.get("url", ""))
        r["products"].update(ptr.get("products", []))
        r["licenses"].add(ptr.get("license", "?"))
        r["pointers"] += 1
    for key, info in owners.items():
        slot(info.get("url") or f"https://github.com/{key}")

    out = [MD_HEADER, "# Upstream skill sources\n\n"]
    out.append(
        "Known sources of IBM-related agent skills, how this catalog uses them, and who "
        "maintains them. Repository, product, license, and usage columns are generated from "
        "skill catalog entries and `catalog/pointers.json`; owner and tracker come from "
        "`catalog/owners.json`.\n\n"
    )
    if not repos:
        out.append("No upstream sources are recorded yet.\n")
        return "".join(out)
    out.append("| Repository | Products | License | In this catalog | Maintained by | Tracker |\n|---|---|---|---|---|---|\n")
    for key in sorted(repos):
        r = repos[key]
        o = owners.get(key, {})
        usage = []
        if r["imported"]:
            usage.append(f"{r['imported']} imported")
        if r["pointers"]:
            usage.append(f"{r['pointers']} pointer(s)")
        tracker = f"[issues]({o['tracker']})" if o.get("tracker") else ""
        out.append(
            f"| [{key}]({r['url']}) | {', '.join(sorted(r['products'])) or '—'} "
            f"| {', '.join(sorted(r['licenses'])) or '—'} | {', '.join(usage) or 'not yet used'} "
            f"| {_md_cell(o.get('maintainer', ''))} | {tracker} |\n"
        )
    return "".join(out)


def build(root: Path) -> dict[str, str]:
    """Return {relative path: content} for every generated file."""
    products = cl.discover(root)
    for p in products:
        if not p.manifest or not p.manifest.get("name") or not p.manifest.get("version"):
            raise BuildError(f"products/{p.slug}: plugin.json missing or incomplete (run validate.py)")
        if not p.skills:
            raise BuildError(f"products/{p.slug}: product has no skills")
    pointers = cl.load_pointers(root)
    owners = cl.load_owners(root)
    return {
        ".claude-plugin/marketplace.json": _json(claude_marketplace(products)),
        ".agents/plugins/marketplace.json": _json(codex_marketplace(products)),
        "CATALOG.md": catalog_md(products, pointers),
        "THIRD_PARTY_NOTICES.md": notices_md(products),
        "UPSTREAMS.md": upstreams_md(products, pointers, owners),
    }


def stale_files(root: Path) -> list[str]:
    stale = []
    for rel, content in build(root).items():
        path = root / rel
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(rel)
    return stale


def write(root: Path) -> list[str]:
    written = []
    for rel, content in build(root).items():
        path = root / rel
        if path.is_file() and path.read_text(encoding="utf-8") == content:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(rel)
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = ap.parse_args(argv)
    root = Path(__file__).resolve().parent.parent
    try:
        if args.check:
            stale = stale_files(root)
            for rel in stale:
                print(f"STALE: {rel} (run: uv run scripts/build_catalog.py)")
            if stale:
                return 1
            print("OK: generated catalog files are up to date")
            return 0
        for rel in write(root):
            print(f"wrote {rel}")
        return 0
    except BuildError as exc:
        print(f"ERROR: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
