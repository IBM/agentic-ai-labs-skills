# --- installer: data loss and interruption ---------------------------------------------------

@pytest.fixture
def src(repo):
    repo.product("db2", version="1.0.0")
    repo.skill("db2", "db2-build")
    repo.skill("db2", "db2-ops")
    return repo.root


def run(src, project, *args):
    return inst.main(["--source-root", str(src), "--project-dir", str(project), *args])


def test_interrupted_first_install_leaves_no_partial_skill(src, tmp_path, monkeypatch):
    project = tmp_path / "p"
    project.mkdir()
    real = shutil.copytree

    def boom(s, d, **kw):
        real(s, d, **kw)
        raise OSError("disk full")

    monkeypatch.setattr(inst.shutil, "copytree", boom)
    assert run(src, project, "--agent", "bob", "--product", "db2") == inst.EXIT_ERROR
    skills = project / ".bob" / "skills"
    assert not skills.exists() or list(skills.iterdir()) == []


def test_interrupted_upgrade_keeps_previous_copy(src, tmp_path, monkeypatch):
    project = tmp_path / "p"
    project.mkdir()
    run(src, project, "--agent", "bob", "--product", "db2")
    (src / "products/db2/skills/db2-build/SKILL.md").write_text("---\nname: db2-build\ndescription: v2\n---\nv2\n")
    real = shutil.copytree

    def boom(s, d, **kw):
        real(s, d, **kw)
        raise OSError("disk full")

    monkeypatch.setattr(inst.shutil, "copytree", boom)
    assert run(src, project, "--agent", "bob", "--product", "db2") == inst.EXIT_ERROR
    installed = project / ".bob/skills/db2-build/SKILL.md"
    assert installed.is_file() and "v2" not in installed.read_text()


def test_force_never_deletes_without_backup(src, tmp_path):
    project = tmp_path / "p"
    project.mkdir()
    mine = project / ".bob/skills/db2-build"
    mine.mkdir(parents=True)
    (mine / "SKILL.md").write_text("precious")
    run(src, project, "--agent", "bob", "--product", "db2", "--force")
    backups = list((project / ".bob/.agentic-ai-labs/backups").rglob("SKILL.md"))
    assert [b.read_text() for b in backups] == ["precious"]


def test_two_forced_runs_in_same_second_keep_both_backups(src, tmp_path, monkeypatch):
    project = tmp_path / "p"
    project.mkdir()
    mine = project / ".bob/skills/db2-build"
    mine.mkdir(parents=True)
    (mine / "SKILL.md").write_text("first")
    run(src, project, "--agent", "bob", "--product", "db2", "--force")
    (mine / "SKILL.md").write_text("second")
    run(src, project, "--agent", "bob", "--product", "db2", "--force")
    texts = sorted(b.read_text() for b in (project / ".bob/.agentic-ai-labs/backups").rglob("SKILL.md"))
    assert texts == ["first", "second"]


