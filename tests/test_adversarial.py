def test_executable_markdown_is_flagged(repo):
    repo.product("ibm-i")
    sdir = repo.imported_skill("ibm-i", "ibmi-jobs", files={"notes.md": "# notes\n"})
    os.chmod(sdir / "notes.md", 0o755)
    # chmod changes the content hash too; record it as a recorded modification
    entry = json.loads((sdir / "catalog-entry.json").read_text())
    entry.update(modified=True, modifications=["test"])
    (sdir / "catalog-entry.json").write_text(json.dumps(entry))
    assert any("executable bit" in e for e in errs(repo))


