def test_record_cannot_vouch_for_a_skill_it_does_not_hash(src, tmp_path):
    """A hand-written record claiming any hash must not let an edited copy be overwritten."""
    project = tmp_path / "p"
    project.mkdir()
    run(src, project, "--agent", "bob", "--product", "db2")
    installed = project / ".bob/skills/db2-build/SKILL.md"
    installed.write_text("edited by user")
    rec_path = project / ".bob/.agentic-ai-labs/skills.install.json"
    rec = json.loads(rec_path.read_text())
    rec["skills"]["db2-build"]["sha256"] = "0" * 64
    rec_path.write_text(json.dumps(rec))
    (src / "products/db2/skills/db2-build/SKILL.md").write_text("---\nname: db2-build\ndescription: v2\n---\nv2\n")
    assert run(src, project, "--agent", "bob", "--product", "db2") == inst.EXIT_WARNINGS
    assert installed.read_text() == "edited by user"
